import 'dart:io';

const _output = 'lib/pages/chat/emoji_catalog.g.dart';
const _latestVersion = 'latest';
const _usageError = 64;
const _versionPrefix = '# Version: ';
const _groupPrefix = '# group: ';
const _fullyQualified = 'fully-qualified';
const _componentGroup = 'Component';
const _fieldSeparator = ';';
const _commentMark = '#';
const ({int first, int last}) _skinTones = (first: 0x1F3FB, last: 0x1F3FF);

Future<void> main(List<String> arguments) async {
  if (arguments case [final input]) {
    await File(_output).writeAsString(
      generateEmoji(await File(input).readAsString()),
    );
    final format = await Process.run('dart', ['format', _output]);
    stdout.write(format.stdout);
    stderr.write(format.stderr);
    exitCode = format.exitCode;
    return;
  }
  stderr
    ..writeln('Usage: dart run tool/generate_emoji.dart <emoji-test.txt>')
    ..writeln('Download it from ${_sourceOf(_latestVersion)}');
  exitCode = _usageError;
}

String _sourceOf(String version) =>
    'https://unicode.org/Public/emoji/$version/emoji-test.txt';

String generateEmoji(String emojiTest) {
  final groups = <List<String>>[];
  String? version;
  var skipped = true;
  for (final line in emojiTest.split('\n')) {
    if (line.startsWith(_versionPrefix)) {
      version = line.substring(_versionPrefix.length).trim();
      continue;
    }
    if (line.startsWith(_groupPrefix)) {
      skipped = line.substring(_groupPrefix.length).trim() == _componentGroup;
      if (!skipped) groups.add([]);
      continue;
    }
    if (skipped || line.startsWith(_commentMark)) continue;
    final fields = line.split(_fieldSeparator);
    if (fields case [
      final codes,
      final status,
      ...,
    ] when status.split(_commentMark).first.trim() == _fullyQualified) {
      final points = [
        for (final code in codes.trim().split(' '))
          if (code.isNotEmpty) int.parse(code, radix: 16),
      ];
      if (points.any((p) => p >= _skinTones.first && p <= _skinTones.last)) {
        continue;
      }
      groups.last.add(String.fromCharCodes(points));
    }
  }
  final source = switch (version) {
    final version? => _sourceOf(version),
    null => throw const FormatException('emoji-test.txt has no version line'),
  };
  final body = StringBuffer()
    ..writeln(
      '// GENERATED by tool/generate_emoji.dart from $source. Do not edit.',
    )
    ..writeln()
    ..writeln('abstract final class EmojiCatalog {')
    ..writeln('  static const List<List<String>> groups = [');
  for (final group in groups) {
    body.writeln('    [');
    for (final emoji in group) {
      body.writeln("      '$emoji',");
    }
    body.writeln('    ],');
  }
  body
    ..writeln('  ];')
    ..writeln('}');
  return '$body';
}
